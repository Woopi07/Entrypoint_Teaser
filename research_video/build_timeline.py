"""Voices every narration line (Kokoro TTS) and builds the timeline.

Writes into <outDir>:
  vo_XX.wav          one clip per line
  timeline.json      line + scene timings (used by audio.py)
and next to this script:
  timeline.js        the same timings for video.html (window.TL)
  ../out/beyond_technical_skills.srt   subtitles file

Usage: python3 build_timeline.py <outDir> [modelDir=/opt/tts]
"""
import json
import os
import sys

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

from script import CAPTIONS, LINES

VOICE, SPEED = 'af_heart', 1.2
LEAD_IN = 0.8        # silence before the first line
GAP = 0.3           # pause between lines in the same scene
SCENE_GAP = 0.45      # pause when the scene changes
TARGET = 150.0     # exact video length in seconds (None = narration + TAIL)
TAIL = 2.3           # hold on the end card after the last line
HOLD = {'title': 0.8, 'comp': 0.3, 'design': 0.4, 'analysis': 0.3, 'corr': 0.4}   # extra time after a scene's last line


def trim(x, sr, thresh=.008):
    idx = np.where(np.abs(x) > thresh)[0]
    if not len(idx):
        return x
    return x[max(0, idx[0] - int(.02 * sr)): min(len(x), idx[-1] + int(.1 * sr))]


def srt_time(t):
    ms = int(round(t * 1000))
    h, ms = divmod(ms, 3600000)
    m, ms = divmod(ms, 60000)
    s, ms = divmod(ms, 1000)
    return f'{h:02d}:{m:02d}:{s:02d},{ms:03d}'


def main():
    out = sys.argv[1]
    model_dir = sys.argv[2] if len(sys.argv) > 2 else '/opt/tts'
    here = os.path.dirname(os.path.abspath(__file__))
    os.makedirs(out, exist_ok=True)
    k = Kokoro(os.path.join(model_dir, 'kokoro-v1.0.int8.onnx'), os.path.join(model_dir, 'voices-v1.0.bin'))

    lines, scenes = [], []
    t = LEAD_IN
    prev = None
    for i, (scene, text) in enumerate(LINES):
        if prev is not None and scene != prev:
            t += SCENE_GAP + HOLD.get(prev, 0)
        elif prev is not None:
            t += GAP
        if scene != prev:
            scenes.append({'id': scene, 'start': round(t - (0 if prev is None else .45), 3)})
        samples, sr = k.create(text, voice=VOICE, speed=SPEED, lang='en-us')
        samples = trim(samples, sr)
        path = os.path.join(out, f'vo_{i:02d}.wav')
        sf.write(path, samples, sr)
        dur = len(samples) / sr
        lines.append({'i': i, 'scene': scene, 'text': CAPTIONS.get(text, text), 'start': round(t, 3), 'end': round(t + dur, 3), 'file': path})
        print(f'{t:6.2f}-{t + dur:6.2f} [{scene:8s}] {text}')
        t += dur
        prev = scene
    total = round(t + TAIL, 2)
    if TARGET:  # pad the end card so the video runs exactly TARGET seconds
        if t + 1.2 > TARGET:
            sys.exit(f'narration ends at {t:.2f}s: too long for a {TARGET}s video')
        total = TARGET
    scenes[0]['start'] = 0
    for a, b in zip(scenes, scenes[1:] + [{'start': total}]):
        a['end'] = b['start']
    tl = {'total': total, 'lines': lines, 'scenes': scenes}

    with open(os.path.join(out, 'timeline.json'), 'w') as f:
        json.dump(tl, f, indent=1)
    js = {'total': total, 'scenes': scenes,
          'lines': [{k2: v for k2, v in ln.items() if k2 != 'file'} for ln in lines]}
    with open(os.path.join(here, 'timeline.js'), 'w') as f:
        f.write('// generated by build_timeline.py\nwindow.TL = ' + json.dumps(js, indent=1) + ';\n')
    os.makedirs(os.path.join(here, '..', 'out'), exist_ok=True)
    with open(os.path.join(here, '..', 'out', 'beyond_technical_skills.srt'), 'w') as f:
        for n, ln in enumerate(lines, 1):
            f.write(f"{n}\n{srt_time(ln['start'])} --> {srt_time(ln['end'] + .25)}\n{ln['text']}\n\n")
    print('total', total, 's')


if __name__ == '__main__':
    main()
